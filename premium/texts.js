function localizeImages() {
  const chosen = document.getElementById('lang-select')?.value || document.documentElement.lang;
  const lang = chosen === 'tr' ? 'tr' : 'en';
  document.querySelectorAll('[data-src-lang]').forEach((img) => (img.src = '/img/' + img.dataset.srcLang.replace('{lang}', lang)));
}
